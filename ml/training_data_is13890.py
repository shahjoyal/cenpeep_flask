"""
training_data_is13890.py — Training examples for the IS-13890 field classifier
===============================================================================
Feeds ml/field_classifier.py's IS13890FieldClassifier. Same contract as
ml/training_data.py:  get_training_data() -> (texts, labels)  parallel lists,
plus get_field_ids() and is_non_field_header().

It is deliberately a SEPARATE module from ml/training_data.py: the CENPEEP /
BEE / ASME classifier and this one never share examples, so adding or
re-labelling anything here cannot change how CENPEEP/BEE columns are detected.

Field ids (keep in sync with routes/upload_is13890.py FIELDS and
src/config/fields.is13890.js — tests/test_is13890_extract.py checks this):

    A VM M FC SUC GCV S            proximate analysis / lab inputs
    T Tdb Twb                      flue-gas outlet temp, ambient dry / wet bulb
    O2 CO2 CO N2                   flue gas analysis at APH inlet
    BL ER Wze                      boiler load, evaporation ratio, atomizing steam
    UBA UFA                        unburnts (LOI) in bottom / fly ash

How the data is built
---------------------
Every row is generated by crossing a few small "axes" (prefix x core phrase x
suffix) with itertools.product(), exactly like ml/training_data.py does.
Extending coverage = adding a word to an axis list.

The OUT_OF_SCOPE class is just as important as the positive classes: the
IS-13890 worksheet is full of CALCULATED rows whose labels look almost
identical to real inputs ("Carbon", "Oxygen", "Weight of dry refuse
collected", "Loss due to formation of CO" ...). They are listed as negatives
so the classifier rejects them instead of forcing them onto the nearest field.

THE "BARE OXYGEN" CONFLICT (fixed)
----------------------------------
A bare element NAME — "Oxygen", "Nitrogen", "Carbon", "Hydrogen" — is how the
worksheet labels its CALCULATED ultimate-analysis rows (formula cells). Those
same words were also being generated as flue-gas examples (O2 / N2 classes),
so one text carried two labels. Resolution: the gas classes (O2, CO2, CO, N2)
now ONLY emit
    * a chemical formula  (O2, CO2, CO, N2 — never ambiguous), or
    * an element name that is accompanied by a gas CONTEXT word
      ("Oxygen at APH inlet", "Oxygen in flue gas", "Nitrogen by difference"),
and the bare element names live exclusively in OUT_OF_SCOPE.
label_conflicts() below returns every text that still carries two labels; the
test-suite asserts it is empty.
"""
from __future__ import annotations

import re
from itertools import product

TRAINING_EXAMPLES: list[tuple[str, str]] = []
OUT_OF_SCOPE_EXAMPLES: list[str] = []


# ── helpers ──────────────────────────────────────────────────────────────────
def _clean(s: str) -> str:
    return ' '.join(s.split())


def _norm_key(s: str) -> str:
    """Same spirit as the classifier's own normaliser — used only to detect
    two examples that would be identical once punctuation/case is removed."""
    s = s.lower().replace('\u2082', '2').replace('\u00b0', ' ')       # O₂ -> o2, degree sign -> space
    return ' '.join(re.sub(r'[^a-z0-9]+', ' ', s).split())


def matrix(field_id: str, *axes):
    """Cross the axes, glue the pieces together as-is (axes carry their own
    spaces), and add every result as a labelled example."""
    for combo in product(*axes):
        text = _clean(''.join(combo))
        if text:
            TRAINING_EXAMPLES.append((text, field_id))


def neg(*axes):
    for combo in product(*axes):
        text = _clean(''.join(combo))
        if text:
            OUT_OF_SCOPE_EXAMPLES.append(text)


