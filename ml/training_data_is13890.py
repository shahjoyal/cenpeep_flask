# ── public API ───────────────────────────────────────────────────────────────
def get_training_data():
    """(texts, labels) — real field ids plus the OUT_OF_SCOPE negative class."""
    seen = set()
    texts, labels = [], []
    for t, l in TRAINING_EXAMPLES:
        key = (_norm_key(t), l)
        if key in seen:
            continue
        seen.add(key)
        texts.append(t)
        labels.append(l)
    for t in OUT_OF_SCOPE_EXAMPLES:
        key = (_norm_key(t), 'OUT_OF_SCOPE')
        if key in seen:
            continue
        seen.add(key)
        texts.append(t)
        labels.append('OUT_OF_SCOPE')
    return texts, labels


def get_field_ids():
    return sorted({l for _, l in TRAINING_EXAMPLES})


def label_conflicts():
    """{normalised text: {labels}} for every example text that carries MORE
    THAN ONE label (including OUT_OF_SCOPE). Must be empty — the "bare Oxygen"
    class of bug. Called by tests/test_is13890_extract.py."""
    by_text = {}
    for t, l in TRAINING_EXAMPLES:
        by_text.setdefault(_norm_key(t), set()).add(l)
    for t in OUT_OF_SCOPE_EXAMPLES:
        by_text.setdefault(_norm_key(t), set()).add('OUT_OF_SCOPE')
    return {k: v for k, v in by_text.items() if len(v) > 1}


# Structural headers that must never be classified, checked before the model.
NON_FIELD_HEADERS = {
    'date', 'time', 'shift', 'hrs', 'hr', 'sr no', 'sl no', 's no', 'remarks', 'remark', 'notes', 'note',
    'particulars', 'symbol', 'uom', 'unit', 'formula', 'calculation', 'inputs', 'input', 'value', 'values',
    'from lab', 'lab value', 'fix', 'constant', 'description', 'parameter', 'parameters', 'method', 'source',
    'sox', 'nox', 'opacity',
}
NON_FIELD_TOKENS = {'sox', 'nox', 'opacity'}


def is_non_field_header(text):
    norm = str(text).strip().lower().replace('.', '').replace('-', ' ').replace(',', ' ')
    norm = ' '.join(norm.split())
    if norm in NON_FIELD_HEADERS:
        return True
    return bool(set(norm.split()) & NON_FIELD_TOKENS)
